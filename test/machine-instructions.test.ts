import { afterEach, describe, expect, test } from "bun:test";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { runSync } from "./jsonl.ts";
import { getStatePaths } from "../src/state.ts";
import { parseTargetSelector, type SyncOptions, type TargetSelector } from "../src/types.ts";
import { decodeOutput } from "./jsonl.ts";

// ADR 0002 (flyingrobots/agent-hub#69): machine instructions are appended to the hub's AGENTS.md
// in a generated rules file that every rules link points at.

const REPO_ROOT = resolve(import.meta.dir, "..");
const tempRoots: string[] = [];
afterEach(() => {
  while (tempRoots.length > 0) rmSync(tempRoots.pop()!, { recursive: true, force: true });
});

const HUB_TEXT = "# Hub rules\n\nShared everywhere.\n";
const MACHINE_TEXT = "## This machine\n\nOnly here.\n";

function sandbox(opts: { xdgConfig?: string } = {}) {
  const home = realpathSync(mkdtempSync(join(tmpdir(), "agent-hub-mi-")));
  tempRoots.push(home);
  const hub = join(home, ".agents");
  for (const d of [join(hub, "skills"), join(home, ".claude"), join(home, ".codex")]) mkdirSync(d, { recursive: true });
  writeFileSync(join(hub, "AGENTS.md"), HUB_TEXT);
  writeFileSync(join(home, ".claude.json"), "{}\n");
  chmodSync(join(home, ".claude.json"), 0o600);
  writeFileSync(join(home, ".codex", "config.toml"), 'model = "gpt-5"\n');
  chmodSync(join(home, ".codex", "config.toml"), 0o600);
  const xdgConfigHome = opts.xdgConfig ? join(home, opts.xdgConfig) : join(home, ".config");
  const base: SyncOptions = {
    hubDir: hub,
    homeDir: home,
    xdgConfigHome,
    xdgStateHome: join(home, ".local", "state"),
  };
  const machineFile = join(xdgConfigHome, "agent-hub", "AGENTS.md");
  const { statePath } = getStatePaths(hub, home, base.xdgStateHome);
  const hash = basename(statePath).replace(/^state-/, "").replace(/\.json$/, "");
  const generated = join(dirname(statePath), `rules-${hash}.md`);
  const rules = { claude: join(home, ".claude", "CLAUDE.md"), codex: join(home, ".codex", "AGENTS.md") };
  return { home, hub, base, machineFile, generated, rules };
}

function writeMachine(path: string, text: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

const sel = (...names: string[]): TargetSelector[] => names.map((n) => parseTargetSelector(n)!);
const out = (r: { stdout: string[]; stderr: string[] }) => [...r.stdout, ...r.stderr].join("\n");

describe("machine instructions (ADR 0002, flyingrobots/agent-hub#69)", () => {
  test("a machine instructions file points every rules link at a generated file: notice, hub text, then machine text", () => {
    const sb = sandbox();
    writeMachine(sb.machineFile, MACHINE_TEXT);
    const r = runSync(sb.base);
    expect(r.exitCode).toBe(0);
    for (const link of Object.values(sb.rules)) expect(readlinkSync(link)).toBe(sb.generated);
    const text = readFileSync(sb.generated, "utf8");
    const notice = text.slice(0, text.indexOf("\n"));
    expect(notice).toContain("Generated by sync-agents");
    expect(notice).toContain(join(sb.hub, "AGENTS.md"));
    expect(notice).toContain(sb.machineFile);
    const body = text.slice(text.indexOf("\n") + 1);
    expect(body.indexOf(HUB_TEXT)).toBeGreaterThanOrEqual(0);
    expect(body.indexOf(MACHINE_TEXT)).toBeGreaterThan(body.indexOf(HUB_TEXT));
    expect(text.endsWith("\n")).toBe(true);
    expect(runSync({ ...sb.base, checkOnly: true }).exitCode).toBe(0);
  });

  test("no machine file, or a whitespace-only one, links the hub AGENTS.md and writes no generated file", () => {
    const sb = sandbox();
    expect(runSync(sb.base).exitCode).toBe(0);
    expect(readlinkSync(sb.rules.claude)).toBe(join(sb.hub, "AGENTS.md"));
    expect(existsSync(sb.generated)).toBe(false);
    writeMachine(sb.machineFile, "  \n\n\t\n");
    expect(runSync({ ...sb.base, checkOnly: true }).exitCode).toBe(0);
    expect(runSync(sb.base).exitCode).toBe(0);
    expect(readlinkSync(sb.rules.claude)).toBe(join(sb.hub, "AGENTS.md"));
    expect(existsSync(sb.generated)).toBe(false);
  });

  test("editing the hub or the machine file makes --check fail naming the generated file, and a sync regenerates it", () => {
    const sb = sandbox();
    writeMachine(sb.machineFile, MACHINE_TEXT);
    expect(runSync(sb.base).exitCode).toBe(0);
    for (const edit of [
      () => writeFileSync(join(sb.hub, "AGENTS.md"), `${HUB_TEXT}\nA new shared rule.\n`),
      () => writeFileSync(sb.machineFile, `${MACHINE_TEXT}\nA new local rule.\n`),
    ]) {
      edit();
      const check = runSync({ ...sb.base, checkOnly: true });
      expect(check.exitCode).toBe(1);
      expect(out(check)).toContain(sb.generated);
      expect(runSync(sb.base).exitCode).toBe(0);
      expect(runSync({ ...sb.base, checkOnly: true }).exitCode).toBe(0);
    }
    const text = readFileSync(sb.generated, "utf8");
    expect(text).toContain("A new shared rule.");
    expect(text).toContain("A new local rule.");
  });

  test("removing the machine file points the rules links back at the hub and removes the generated file", () => {
    const sb = sandbox();
    writeMachine(sb.machineFile, MACHINE_TEXT);
    expect(runSync(sb.base).exitCode).toBe(0);
    rmSync(sb.machineFile);
    expect(runSync({ ...sb.base, checkOnly: true }).exitCode).toBe(1);
    expect(runSync(sb.base).exitCode).toBe(0);
    for (const link of Object.values(sb.rules)) expect(readlinkSync(link)).toBe(join(sb.hub, "AGENTS.md"));
    expect(existsSync(sb.generated)).toBe(false);
    expect(runSync({ ...sb.base, checkOnly: true }).exitCode).toBe(0);
  });

  test("a generated file deleted by hand is recreated by the next sync", () => {
    const sb = sandbox();
    writeMachine(sb.machineFile, MACHINE_TEXT);
    expect(runSync(sb.base).exitCode).toBe(0);
    rmSync(sb.generated);
    expect(runSync({ ...sb.base, checkOnly: true }).exitCode).toBe(1);
    expect(runSync(sb.base).exitCode).toBe(0);
    expect(readFileSync(sb.generated, "utf8")).toContain(MACHINE_TEXT);
    expect(readlinkSync(sb.rules.claude)).toBe(sb.generated);
    expect(runSync({ ...sb.base, checkOnly: true }).exitCode).toBe(0);
  });

  test("--dry-run and --explain name the machine instructions file and write no generated file", () => {
    const sb = sandbox();
    writeMachine(sb.machineFile, MACHINE_TEXT);
    for (const mode of [{ dryRun: true }, { explain: true }] as const) {
      const r = runSync({ ...sb.base, ...mode });
      expect(r.exitCode).toBe(0);
      expect(out(r)).toContain(sb.machineFile);
      expect(existsSync(sb.generated)).toBe(false);
      expect(existsSync(sb.rules.claude)).toBe(false);
    }
  });

  test("a scoped run never removes a generated file an excluded target's rules link still points at", () => {
    const sb = sandbox();
    writeMachine(sb.machineFile, MACHINE_TEXT);
    expect(runSync(sb.base).exitCode).toBe(0);
    rmSync(sb.machineFile);
    expect(runSync({ ...sb.base, targets: sel("claude") }).exitCode).toBe(0);
    expect(readlinkSync(sb.rules.claude)).toBe(join(sb.hub, "AGENTS.md"));
    expect(readlinkSync(sb.rules.codex)).toBe(sb.generated);
    expect(existsSync(sb.generated)).toBe(true);
    expect(runSync(sb.base).exitCode).toBe(0);
    expect(existsSync(sb.generated)).toBe(false);
  });

  test("the machine instructions file follows $XDG_CONFIG_HOME", () => {
    const sb = sandbox({ xdgConfig: "xdg-config" });
    writeMachine(join(sb.home, ".config", "agent-hub", "AGENTS.md"), "## Ignored\n");
    writeMachine(sb.machineFile, MACHINE_TEXT);
    expect(runSync(sb.base).exitCode).toBe(0);
    const text = readFileSync(sb.generated, "utf8");
    expect(text).toContain(MACHINE_TEXT);
    expect(text).not.toContain("## Ignored");
  });

  test("--project ignores the machine instructions file", () => {
    const sb = sandbox();
    writeMachine(sb.machineFile, MACHINE_TEXT);
    const repo = join(sb.home, "repo");
    mkdirSync(join(repo, ".agents"), { recursive: true });
    writeFileSync(join(repo, ".agents", "AGENTS.md"), "# Project rules\n");
    const p = Bun.spawnSync(["bun", join(REPO_ROOT, "src", "cli.ts"), "--project", "--dir", repo], {
      env: {
        PATH: process.env.PATH ?? "/usr/bin:/bin",
        HOME: sb.home,
        XDG_CONFIG_HOME: join(sb.home, ".config"),
        XDG_STATE_HOME: join(sb.home, ".local", "state"),
        BUN_RUNTIME_TRANSPILER_CACHE_PATH: "0",
      },
      stdout: "pipe",
      stderr: "pipe",
      timeout: 30_000,
    });
    const decoded = decodeOutput(p.stdout.toString(), p.stderr.toString());
    expect(decoded.stdout + decoded.stderr).not.toContain(sb.machineFile);
    expect(p.exitCode).toBe(0);
    expect(readlinkSync(join(repo, "CLAUDE.md"))).toBe(join(".agents", "AGENTS.md"));
    expect(existsSync(sb.generated)).toBe(false);
  });
});
