import { existsSync, readFileSync, rmSync, statSync } from "node:fs";
import { join } from "node:path";
import { resolveLinkTargetId } from "./adapters.ts";
import { atomicWriteDurable, canonicalizeHubPath, physicalPath } from "./paths.ts";
import type { OwnershipStateV2, PlannedOp } from "./types.ts";

/**
 * Machine instructions (ADR 0002): an optional `<configBase>/agent-hub/AGENTS.md` appended to the
 * hub's `AGENTS.md` in a generated rules file in the state directory. Every rules link points at
 * that file while the machine file holds anything but whitespace, and at the hub's otherwise.
 *
 * The generated file is derived output, not an owned target: it is written atomically and is not
 * journaled, because a run interrupted at any point converges on the next one. Its path and the
 * machine file's are physical (symlinks resolved), so another spelling of HOME or
 * XDG_STATE_HOME names the same file and is not drift.
 */
export type MachineRulesPlan = {
  /** What rules links should point at in this run. */
  rulesSrc: string;
  machineFile: string;
  generatedPath: string;
  /** Write or keep the generated file; applied before any link. */
  writeOp: PlannedOp | null;
  /** Remove a generated file no longer wanted; applied after every link (see planMachineRulesRemoval). */
  removeOp: PlannedOp | null;
  content: Buffer | null;
  /** Why the generated file is not wanted, when it is not. */
  unwantedBecause: string | null;
};

export function machineInstructionsPath(configBase: string): string {
  return join(configBase, "agent-hub", "AGENTS.md");
}

/** The generated rules: a notice, the hub's bytes, a marker, then the machine file's bytes, unchanged. */
export function generatedRulesContent(hubRules: string, hubBytes: Buffer, machineFile: string, machineBytes: Buffer): Buffer {
  const LF = Buffer.from("\n");
  const nl = (b: Buffer) => (b.length > 0 && b[b.length - 1] === 0x0a ? b : Buffer.concat([b, LF]));
  const notice = `<!-- Generated by sync-agents from ${hubRules} and ${machineFile}. Edit those files, not this one: the next sync overwrites it. -->\n\n`;
  const marker = `\n<!-- Machine instructions from ${machineFile}: this machine only. -->\n\n`;
  return Buffer.concat([Buffer.from(notice), nl(hubBytes), Buffer.from(marker), nl(machineBytes)]);
}

function readIfFile(path: string): Buffer | null {
  if (!existsSync(path)) return null;
  if (!statSync(path).isFile()) throw new Error(`machine instructions ${path} is not a regular file`);
  return readFileSync(path);
}

export function planMachineRules(
  canonicalHubPath: string,
  homeDir: string,
  configBase: string,
  rulesPath: string,
): MachineRulesPlan {
  const hubRules = join(canonicalHubPath, "AGENTS.md");
  const machineFile = canonicalizeHubPath(machineInstructionsPath(configBase), homeDir, "/");
  const generatedPath = canonicalizeHubPath(rulesPath, homeDir, "/");
  const hubBytes = existsSync(hubRules) && statSync(hubRules).isFile() ? readFileSync(hubRules) : null;
  const machineBytes = readIfFile(machineFile);
  const machineEmpty = machineBytes === null || machineBytes.toString("utf8").trim() === "";

  if (hubBytes !== null && !machineEmpty) {
    const content = generatedRulesContent(hubRules, hubBytes, machineFile, machineBytes!);
    const current = existsSync(generatedPath) ? readFileSync(generatedPath) : null;
    const same = current !== null && current.equals(content);
    return {
      rulesSrc: generatedPath,
      machineFile,
      generatedPath,
      content,
      removeOp: null,
      unwantedBecause: null,
      writeOp: {
        domain: "rules",
        action: same ? "keep" : "rules-generate",
        status: same ? "ok" : "change",
        destination: generatedPath,
        observed: current === null ? "absent" : same ? "generated rules are current" : "generated rules are stale",
        intended: `${hubRules} followed by ${machineFile}`,
        ownershipBasis: "generated",
        reason: `machine instructions in ${machineFile} extend ${hubRules}${same ? "" : current === null ? "; writing the generated rules" : "; regenerating"}`,
        targetMutation: !same,
        ledgerMutation: false,
      },
    };
  }

  return {
    rulesSrc: hubRules,
    machineFile,
    generatedPath,
    content: null,
    writeOp: null,
    removeOp: null,
    unwantedBecause:
      hubBytes === null
        ? `the hub has no AGENTS.md, so there are no rules for ${machineFile} to extend`
        : `no machine instructions in ${machineFile}; rules links point at ${hubRules} again`,
  };
}

/**
 * Plan removal of a generated file no longer wanted, once the link plans are known. A ledger
 * record whose link physically leads to the file and that no link plan of this run touches (an
 * excluded target's) keeps the file. Records this run re-points or prunes do not.
 */
export function planMachineRulesRemoval(
  plan: MachineRulesPlan,
  state: OwnershipStateV2,
  linkDestinations: Iterable<string>,
): PlannedOp | null {
  if (plan.unwantedBecause === null || !existsSync(plan.generatedPath)) return null;
  const touched = new Set([...linkDestinations].map((d) => physicalPath(d)));
  const target = physicalPath(plan.generatedPath);
  const held = Object.entries(state.links).some(
    ([dst, rec]) => rec.kind === "rules" && physicalPath(rec.target) === target && !touched.has(physicalPath(dst)),
  );
  if (held) return null;
  return {
    domain: "rules",
    action: "rules-remove",
    status: "change",
    destination: plan.generatedPath,
    observed: "generated rules present",
    intended: "absent",
    ownershipBasis: "generated",
    reason: plan.unwantedBecause,
    targetMutation: true,
    ledgerMutation: false,
  };
}

export function applyMachineRulesWrite(plan: MachineRulesPlan): void {
  if (plan.content === null) throw new Error("no generated rules to write");
  // Owner-only: the machine file may hold what other local users should not read.
  atomicWriteDurable(plan.generatedPath, plan.content, 0o600, 0o600);
}

export function applyMachineRulesRemove(plan: MachineRulesPlan): void {
  rmSync(plan.generatedPath, { force: true });
}
